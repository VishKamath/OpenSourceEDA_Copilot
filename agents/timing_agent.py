"""
agents/timing_agent.py: Automated SDC Constraint Generator & Timing Signoff
============================================================================
Hardware Mental Model:
- SDC Generator: Clock Tree & I/O Budgeting Engine.
  Synthesizes setup/hold time windows, arrival uncertainties, and external delays
  for chip boundary pins.
"""

from __future__ import annotations

from pathlib import Path
from typing import List, Optional


def generate_sdc_constraints(
    clock_port: str = "clk",
    clock_period_ns: float = 10.0,
    uncertainty_ns: float = 0.2,
    input_delay_ns: Optional[float] = None,
    output_delay_ns: Optional[float] = None,
    input_ports: Optional[List[str]] = None,
    output_ports: Optional[List[str]] = None,
    prompt_spec: Optional[Any] = None,
) -> str:
    """
    Synthesizes standard Synopsys Design Constraints (SDC).
    Specifies clock periods, uncertainties, and I/O boundary arrival constraints.
    Incorporate user prompt specificity if provided.
    """
    if prompt_spec:
        if getattr(prompt_spec, "clock_port", None):
            clock_port = prompt_spec.clock_port
        if getattr(prompt_spec, "clock_period_ns", None):
            clock_period_ns = prompt_spec.clock_period_ns
        if getattr(prompt_spec, "uncertainty_ns", None) is not None:
            uncertainty_ns = prompt_spec.uncertainty_ns
        if getattr(prompt_spec, "input_delay_ns", None) is not None:
            input_delay_ns = prompt_spec.input_delay_ns
        if getattr(prompt_spec, "output_delay_ns", None) is not None:
            output_delay_ns = prompt_spec.output_delay_ns

    inp_delay = input_delay_ns if input_delay_ns is not None else round(clock_period_ns * 0.2, 2)
    out_delay = output_delay_ns if output_delay_ns is not None else round(clock_period_ns * 0.2, 2)

    lines: List[str] = [
        f"###############################################################################",
        f"# Automated SDC Constraints Generated by Agentic EDA Copilot",
        f"# Target Frequency: {1000.0 / clock_period_ns:.2f} MHz (Period: {clock_period_ns} ns)",
        f"###############################################################################",
        f"",
        f"# 1. Clock Definition",
        f"create_clock -name {clock_port} -period {clock_period_ns} [get_ports {clock_port}]",
        f"",
        f"# 2. Clock Uncertainty (Skew + Jitter Margin)",
        f"set_clock_uncertainty {uncertainty_ns} [get_clocks {clock_port}]",
        f"",
        f"# 3. Input Delay Budget (20% cycle default)",
    ]

    if input_ports:
        port_list = " ".join(input_ports)
        lines.append(f"set_input_delay {inp_delay} -clock {clock_port} [get_ports {{{port_list}}}]")
    else:
        lines.append(f"set_input_delay {inp_delay} -clock {clock_port} [all_inputs]")

    lines.append("")
    lines.append(f"# 4. Output Delay Budget (20% cycle default)")
    if output_ports:
        port_list = " ".join(output_ports)
        lines.append(f"set_output_delay {out_delay} -clock {clock_port} [get_ports {{{port_list}}}]")
    else:
        lines.append(f"set_output_delay {out_delay} -clock {clock_port} [all_outputs]")

    lines.append("")
    return "\n".join(lines) + "\n"
